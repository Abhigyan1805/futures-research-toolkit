"""Collect each module's results/<module>/headline.json into docs/RESULTS.md."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = [("fairvalue", "Fair value engine"), ("regimes", "Spread/butterfly regimes"),
           ("candles", "Candlestick patterns")]


def main() -> None:
    lines = ["# Results", "", "Generated by `make e2e` from real data. Do not edit by hand.", ""]
    for mod, title in MODULES:
        p = ROOT / "results" / mod / "headline.json"
        lines += [f"## {title} (`{mod}`)", ""]
        if not p.exists():
            lines += ["_not run_", ""]
            continue
        for k, v in json.loads(p.read_text()).items():
            lines.append(f"- **{k}**: {v}")
        lines.append("")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
